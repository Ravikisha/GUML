/// `count` -> `setCount`
pub(crate) fn setter(name: &str) -> String {
    let mut c = name.chars();
    match c.next() {
        Some(f) => format!("set{}{}", f.to_uppercase(), c.as_str()),
        None => "set".to_string(),
    }
}

/// PascalCase component name from a page name.
pub(crate) fn component_name(raw: &str) -> String {
    let mut out = String::new();
    let mut upper = true;
    for ch in raw.chars() {
        if ch.is_alphanumeric() {
            if upper {
                out.extend(ch.to_uppercase());
                upper = false;
            } else {
                out.push(ch);
            }
        } else {
            upper = true;
        }
    }
    if out.is_empty() || out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("Page{out}")
    } else {
        out
    }
}

/// Invariant 3: a construct a backend cannot lower is *reported*, never silently dropped.
///
/// The backend names itself, because "cannot lower" now means different things in different
/// backends. In React it is a gap to be filled later; in `html` it is permanent and architectural —
/// there is no JavaScript, so there will never be an `onClick`. A message that said "does not yet"
/// about the second case would be telling the reader to wait for something that is not coming.
pub(crate) fn unsupported_in(
    diags: &mut Diagnostics,
    backend: &str,
    span: Span,
    what: impl AsRef<str>,
) {
    let mut d = guml_diagnostics::Diagnostic::warning(
        guml_diagnostics::Code::UnknownTag,
        format!("`{backend}` backend: {}", what.as_ref()),
        span,
    );
    d.severity = Severity::Warning;
    d.help = Some(match backend {
        "html" => "the emitted markup marks the gap with `data-guml-inert`; a construct that needs a runtime cannot work in a no-JavaScript backend".into(),
        _ => "tracked in ROADMAP.md Phase 3; the emitted file marks the gap with a TODO".to_string(),
    });
    diags.push(d);
}

/// The React backend's shorthand, kept so its call sites read unchanged.
pub(crate) fn unsupported(diags: &mut Diagnostics, span: Span, what: impl AsRef<str>) {
    unsupported_in(diags, "react", span, format!("does not yet lower {}", what.as_ref()));
}

pub(crate) fn modifiers_of(el: &Element) -> Vec<&str> {
    el.positionals
        .iter()
        .filter_map(|p| match p {
            Positional::Modifier(m) => Some(m.as_str()),
            _ => None,
        })
        .collect()
}

/// The column headers a repeater declares with `cols=`, or empty.
///
/// # Why `cols` and why a string here
///
/// `cols` is a numeric layout attribute everywhere else — `grid cols=3` sets a column count. On a repeater
/// it lists the headers instead: `table invoices cols="Client, Amount, Due, Paid"`. One attribute name, two
/// types, decided by the tag.
///
/// That asymmetry is deliberate and it is the reason the type checker had to learn per-tag attribute types:
/// a grid's columns are a *count* the compiler generates, and a table's columns are *names* only the author
/// knows. Reusing the name keeps the surface small, and reusing the meaning would have been wrong.
///
/// Comma-separated rather than a repeated attribute, because a duplicate attribute is `GUML0082` and
/// changing that to allow one exception would weaken a rule that catches real mistakes.
///
/// Trailing empties are dropped, so `cols="A, B,"` is two columns — a trailing comma in a hand-written list
/// is a typo, not a request for a blank column.
pub fn column_headers(el: &Element) -> Vec<String> {
    let Some(value) = el.attr("cols") else { return Vec::new() };
    let Some(text) = value.as_text() else { return Vec::new() };
    text.split(',').map(str::trim).filter(|s| !s.is_empty()).map(str::to_string).collect()
}

/// The `<thead>` block for a tabular repeater, or `None` when it declares no `cols=`.
///
/// Shared, and by invariant 8 it has to be: three backends emit a table, and three copies of "a header cell
/// carries `scope=\"col\"`" is three chances for one of them to forget. The only per-backend difference is
/// the attribute name — `className` in JSX, `class` everywhere else — so that is the parameter.
///
/// `scope="col"` is the header/cell association itself. It is exactly the kind of plumbing invariant 4 puts
/// in the compiler rather than in the source: a model asked to remember it will forget, and the failure is
/// invisible until someone uses a screen reader.
pub(crate) fn table_head(el: &Element, pad: &str, attr: &str) -> Option<String> {
    let headers = column_headers(el);
    if headers.is_empty() {
        return None;
    }
    let class = theme::active().classes("th", &[]);
    let class_attr = if class.is_empty() { String::new() } else { format!(" {attr}={class:?}") };
    let mut out = format!("{pad}  <thead>\n{pad}    <tr>\n");
    for h in &headers {
        let _ =
            writeln!(out, "{pad}      <th scope=\"col\"{class_attr}>{}</th>", html_escape_text(h));
    }
    let _ = write!(out, "{pad}    </tr>\n{pad}  </thead>\n");
    Some(out)
}

/// Report what is wrong with a tabular repeater's `cols=`, if anything.
///
/// Two failures, and the second is the nastier one:
///
/// * **No `cols=` at all.** A data table with no header row is an accessibility defect rather than a style
///   choice — a screen reader has nothing to announce a cell against. The compiler cannot invent the names,
///   because only the author knows what the columns mean, so it reports.
/// * **A count that does not match the row template.** Every header would sit one column left of its data.
///   That reads as correct at a glance, which makes it worse than an unlabelled table.
pub(crate) fn check_columns(diags: &mut Diagnostics, backend: &str, el: &Element, cells: usize) {
    let headers = column_headers(el);
    if headers.is_empty() {
        unsupported_in(
            diags,
            backend,
            el.span,
            "a `table` with no `cols=`, so its columns have no headers and a screen reader cannot \
             associate a cell with one — add `cols=\"First, Second\"`",
        );
    } else if headers.len() != cells {
        unsupported_in(
            diags,
            backend,
            el.span,
            format!(
                "`cols=` names {} column(s) but the row template renders {cells}; the headers would not \
                 line up with the data",
                headers.len()
            ),
        );
    }
}

/// Minimal text escaping for a header, which is author-written text in an element body.
fn html_escape_text(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

/// Classes from the *layout* attributes — `cols`, `gap`, `w`.
///
/// # Why shared, and the drift that made it necessary
///
/// These are presentation, so they join the class list rather than becoming DOM properties: `cols={3}` on a
/// `<section>` is not valid HTML, which `tsc` caught on the landing fixture. React had that logic and no
/// other backend did, so `grid cols=3` came out as `grid gap-6 md:grid-cols-3` in React and plain
/// `grid gap-6` everywhere else — the same document with three columns in one representation and an
/// unspecified number in the others. Nothing failed, because each backend's snapshot only agreed with
/// itself, and the html output is the one a no-JavaScript build ships.
///
/// A repeater's `cols` is skipped: there it is the header list, not a column count.
pub fn layout_classes(el: &Element) -> Vec<String> {
    let mut out = Vec::new();
    for a in &el.attrs {
        match a.name.as_str() {
            "cols" if !is_tabular(el) && el.tag != "list" => {
                if let Value::Num(n) = &a.value {
                    out.push(format!("grid gap-6 md:grid-cols-{}", *n as i64));
                }
            }
            "gap" => {
                if let Value::Num(n) = &a.value {
                    out.push(format!("gap-{}", *n as i64));
                }
            }
            "w" => {
                if let Some(w) = a.value.as_text() {
                    out.push(format!("max-w-{w}"));
                }
            }
            _ => {}
        }
    }
    out
}

/// A tag's theme classes plus its layout classes, deduplicated — what every backend should put in `class`.
pub fn class_list(el: &Element) -> String {
    let mods: Vec<&str> = el
        .positionals
        .iter()
        .filter_map(|p| match p {
            Positional::Modifier(m) => Some(m.as_str()),
            _ => None,
        })
        .collect();
    let mut all = theme::active().classes(&el.tag, &mods);
    for extra in layout_classes(el) {
        if !all.is_empty() {
            all.push(' ');
        }
        all.push_str(&extra);
    }
    dedupe_classes(&all)
}

/// Whether this repeater should lower to a real `<table>`.
///
/// `table` always does, and `list` never does. The tag is the author's statement of intent, and honouring it
/// is what makes `table` mean anything: it emitted a `<ul>` in every backend until now, so a document that
/// asked for tabular data got a list of rows with no columns, no headers and no header association for a
/// screen reader. `scripts/render-emitted.mjs` has asserted "table without header cells" since it was
/// written and the assertion had never once fired, because no `<table>` was ever emitted to test.
pub fn is_tabular(el: &Element) -> bool {
    el.tag == "table"
}

