/**
 * The component vocabulary, read straight out of the compiler. The docs table
 * can therefore never drift from what the parser will accept.
 */
function registry() {
  let raw;
  try {
    raw = execFileSync("cargo", ["run", "-q", "-p", "guml-cli", "--", "registry"], {
      cwd: repoRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
  } catch {
    console.warn("! could not read the registry from the compiler");
    return { components: [], modifiers: [] };
  }

  const components = [];
  let modifiers = [];
  for (const line of raw.split(/\r?\n/)) {
    if (line.startsWith("modifiers:")) {
      modifiers = line.replace("modifiers:", "").trim().split(/\s+/);
      continue;
    }
    const m = /^(\S+)\s+(\S+)\s+(.*)$/.exec(line.trim());
    if (m) components.push({ name: m[1], kind: m[2], doc: m[3] });
  }
  return { components, modifiers };
}

