/// Each collection paired with the single boolean field of its row type.
///
/// `.open`/`.done` are the language's way of saying "not in the terminal state" / "in it", and until
/// this existed they lowered to a hardcoded `!it.done`. That is only correct for authors who happen to
/// name the field `done`: a Phase 0 example modelling invoices as `{id, client, amount:number,
/// paid:bool, due:date}` compiled to `invoices.filter((it) => !it.done).length`, which is always zero,
/// with no diagnostic. The analyser now rejects the ambiguous and missing cases (`GUML0065`), so a
/// collection reaching here has exactly one candidate.
///
/// Shared by all three backends deliberately. Three copies of this loop is three chances for React and
/// Svelte to filter on different fields for the same document.
/// Retry with exponential backoff, emitted once per file when the document fetches anything.
///
/// Convention-as-compression at its least glamorous and most useful: every real application needs
/// this, nobody writes it on the first pass, and the hand-written version is usually wrong in one of
/// three ways this one is not.
///
/// * **Only idempotent requests are retried.** A repeated `POST` with no idempotency key creates two
///   rows, so the decision belongs to the *method* and is made here rather than left to a caller who
///   can set the flag on the wrong request.
/// * **Only 5xx and transport failures are retried.** A 404 or a 422 will answer the same way however
///   many times it is asked; retrying it only delays the error the author needs to see.
/// * **An abort is not a failure.** Retrying after the component unmounted is the leak the
///   `AbortController` existed to prevent.
///
/// Emitted rather than imported because a compiled page has no GUML runtime dependency — that is what
/// compiling means here. It costs ~90 tokens of *output* once per file and zero tokens of input.
///
/// Two spellings because the React backend emits TypeScript and the Svelte one emits plain JavaScript.
/// They are held together by a test on the policy rather than on the text, since the type annotations
/// are the only thing that may legitimately differ.
pub const RETRY_TS: &str = r#"/**
 * `fetch` with exponential backoff. Generated by the GUML compiler.
 *
 * Retries only what is safe to repeat — idempotent methods, and only on a transport failure or a 5xx.
 * A 4xx will answer the same way next time, and an abort means the caller no longer wants the answer.
 */
async function retrying(url: string, init: RequestInit = {}, tries = 3): Promise<Response> {
  const idempotent = !init.method || ["GET", "HEAD", "PUT", "DELETE"].includes(init.method);
  let wait = 300;
  for (let attempt = 1; ; attempt++) {
    const last = attempt >= tries || !idempotent;
    try {
      const res = await fetch(url, init);
      if (res.ok || res.status < 500 || last) return res;
    } catch (err) {
      if (last || (err instanceof Error && err.name === "AbortError")) throw err;
    }
    await new Promise((resolve) => setTimeout(resolve, wait));
    wait *= 2;
  }
}

"#;

