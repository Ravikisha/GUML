/// A React error boundary, emitted **only** for a document that uses an escape hatch.
///
/// # Why the rule is that narrow
///
/// The tempting version is "wrap every page, it costs nothing". It costs something — ~25 lines of output
/// on every page — and more importantly it would be *ceremony*: an error boundary catches errors thrown
/// during render, and the render code here is generated by the compiler from a typechecked expression
/// tree. There is no user code in it to throw.
///
/// Except in exactly one place. A `js` block and a `raw react` block are the two constructs where the
/// compiler's guarantees stop by design — the body is emitted verbatim, never lexed, never checked. That
/// code *can* throw during render, and when it does React unmounts the whole tree and the page goes
/// blank. So the boundary exists to contain the code the compiler does not check, and emitting it
/// anywhere else would be padding.
///
/// The fallback deliberately names the escape hatch as the likely cause. A generic "Something went wrong"
/// sends the reader looking through generated code; naming the one construct the compiler did not verify
/// is the difference between a message and a lead.
pub const ERROR_BOUNDARY_TSX: &str = r#"/**
 * Error boundary. Generated by the GUML compiler.
 *
 * Emitted because this document uses a `js` or `raw` escape hatch — the two places where the compiler's
 * guarantees stop and the body is passed through verbatim. Generated render code cannot throw; that code
 * can, and without a boundary one throw blanks the entire page.
 */
class GumlBoundary extends Component<{ children: ReactNode }, { error: Error | null }> {
  state: { error: Error | null } = { error: null };

  static getDerivedStateFromError(error: Error) {
    return { error };
  }

  render() {
    if (!this.state.error) return this.props.children;
    return (
      <div role="alert" className="rounded-md border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700">
        <p className="font-medium">This view could not render.</p>
        <p className="mt-1">
          {this.state.error.message} — the most likely cause is a `js` or `raw` block, which the GUML
          compiler passes through without checking.
        </p>
      </div>
    );
  }
}

"#;

/// Whether a document uses an escape hatch, and therefore warrants an error boundary.
pub fn uses_escape_hatch(els: &[Element]) -> bool {
    els.iter().any(|el| matches!(el.tag.as_str(), "js" | "raw") || uses_escape_hatch(&el.children))
}

/// The path prefix a mutation on this resource should invalidate.
///
/// The resource's own URL up to its first interpolation, so `PATCH /api/tasks/{id}` invalidates
/// `/api/tasks` — the list the row came from. Trimming at the brace is what makes one mutation invalidate
/// the collection rather than only the row's own URL, which nothing was caching.
pub fn invalidation_prefix(url: &str) -> String {
    let base = url.split('{').next().unwrap_or(url);
    base.trim_end_matches('/').to_string()
}

/// A class list with duplicates removed, first occurrence winning.
///
/// Needed because two sources contribute classes to one element: the theme's rule for the tag, and the
/// layout attributes (`cols`, `gap`, `w`) that a backend folds in afterwards. They overlap by
/// construction — `cols=` has to emit `grid gap-6` so that `card cols=3` becomes a grid, and the `grid`
/// *tag*'s own rule says `grid gap-6` too, so `grid cols=3` produced
/// `class="grid gap-6 grid gap-6 md:grid-cols-3"`.
///
/// Harmless to a browser and not harmless to a reader: emitted code is something a person opens, and a
/// duplicated utility reads as a compiler that does not know what it emitted. Order is preserved because
/// utility frameworks resolve conflicts by source order, so reordering could change the rendering.
pub(crate) fn dedupe_classes(classes: &str) -> String {
    let mut seen = std::collections::BTreeSet::new();
    classes.split_whitespace().filter(|c| seen.insert(*c)).collect::<Vec<_>>().join(" ")
}

/// The HTML element a GUML tag lowers to. `None` means no backend lowers it yet.
///
/// # Why this is shared
///
/// It was two tables. `react.rs` mapped `nav` to `<nav>`, `hero` to `<header>` and `footer` to
/// `<footer>`; `html.rs` had a `_ => "div"` fallback and so emitted a `<div>` for all three. The
/// no-JavaScript output therefore had *no landmarks* — a screen-reader user could not jump to the
/// navigation on a page where the React build let them.
///
/// The two backends already share `classes()`, and a test holds them to producing the same class
/// strings, on the argument that "GUML is an IR" has to be a claim about the language rather than about
/// one emitter. The same argument applies at least as strongly to the *element*, which is what carries
/// the semantics: `every_tag_lowers_to_the_same_element_in_every_backend` now pins it.
///
/// Attributes that depend on the element's own content — a `btn`'s `type`, a `link`'s `href`, an
/// `img`'s `src` — stay with each backend, because they are not a property of the tag.
pub(crate) fn element_for(tag: &str) -> Option<&'static str> {
    Some(match tag {
        "card" | "row" | "col" | "grid" | "skeleton" => "div",
        "section" => "section",
        "nav" => "nav",
        "hero" => "header",
        "footer" => "footer",
        "form" => "form",
        "sidebar" => "aside",
        "h" | "h2" => "h2",
        "h1" => "h1",
        "h3" => "h3",
        // `metric` is a `TagKind::Text` — its line remainder is prose — so it belongs with the other
        // text tags. React emitted a `<div>` for it while this backend emitted a `<p>`; unifying them
        // meant picking one, and a block `div` wrapping a single run of text was the wrong half.
        "p" | "head" | "empty" | "note" | "metric" => "p",
        "text" | "badge" | "avatar" => "span",
        "label" => "label",
        "btn" => "button",
        "link" => "a",
        "check" | "toggle" | "input" => "input",
        "select" => "select",
        "option" => "option",
        "divider" => "hr",
        "img" => "img",
        "progress" => "progress",
        "step" => "li",
        "stepper" => "ol",
        "menu" => "ul",
        "toolbar" | "alert" | "modal" | "drawer" | "toast" => "div",
        "breadcrumb" | "pagination" => "nav",
        "stat" => "dl",
        _ => return None,
    })
}

/// The vocabulary this process compiles against.
///
/// A process-wide value rather than a parameter on `Backend::emit`, for exactly the reason
/// [`theme::active`] gives about the class table: the question "what is this tag" is asked from a dozen
/// places across five backends, several of them deep inside recursive renderers that would each have to
/// grow a `&Registry` argument. A single override point keeps the change here rather than in every
/// emitter.
///
/// Defaults to the builtins, so a caller that never sets one behaves as before. `set` is write-once per
/// process: a compiler run has one vocabulary, and switching mid-run would emit a document against two.
///
/// Before this existed, a backend could only see the *builtin* vocabulary — so a loaded component's
/// `capabilities` were invisible to the `html` backend's runtime check, and its `element` could not be
/// read at all, which is why a registry package validated documents it could not compile.
static ACTIVE_REGISTRY: std::sync::OnceLock<guml_registry::Registry> = std::sync::OnceLock::new();

pub fn registry() -> &'static guml_registry::Registry {
    ACTIVE_REGISTRY.get_or_init(guml_registry::Registry::builtin)
}

/// Install the vocabulary for this process. Returns `Err` with the registry if one is already active.
pub fn set_registry(reg: guml_registry::Registry) -> Result<(), Box<guml_registry::Registry>> {
    ACTIVE_REGISTRY.set(reg).map_err(Box::new)
}

/// What a tag lowers to, when the registry says and the compiler does not already know.
///
/// Returns `(element, import)`. `None` means no loaded entry describes it, and the caller falls back to
/// [`element_for`] and then to reporting the gap.
pub(crate) fn custom_element(tag: &str) -> Option<(&'static str, Option<&'static str>)> {
    let def = registry().get(tag)?;
    let element = def.element.as_deref()?;
    Some((element, def.import.as_deref()))
}

/// Whether a tag cannot work without client-side JavaScript, per its registry entry.
///
/// Read from the registry rather than matched against a list in each backend. Three backends asking
/// "does this need a runtime" is three lists to forget to update; `capabilities.needs_runtime` is the
/// entry's own answer, and a component that declares it gets the right treatment in every backend
/// without any backend naming it.
pub(crate) fn needs_runtime(tag: &str) -> bool {
    registry().get(tag).is_some_and(|c| c.capabilities.needs_runtime)
}

/// The choices a `select` offers, in document order.
///
/// # Why this is shared rather than per-backend
///
/// A `select` emitted **no options at all** until this existed. Every backend produced
/// `<select value={status} onChange={…}>` and nothing inside it — a dropdown with nothing to choose,
/// which is not a partial lowering but a wrong one. It survived because no fixture used `select` with a
/// domain, so neither the snapshots nor `typecheck-emitted` ever saw the empty case.
///
/// Two sources, in order:
///
/// 1. **Authored `option` children.** This is the shape a model reaches for unprompted, because it is
///    the shape HTML has. Accepting it costs nothing and removes an entire class of generation failure.
/// 2. **The bound state's enumerated domain.** `state status=open|closed` already names the choices, and
///    repeating them as children would be the per-line overhead GUML exists to remove.
///
/// The two cannot disagree, because `sema` checks authored options against the domain when there is one
/// and *derives* the domain from them when there is not.
///
/// Deliberately not a desugar pass that rewrites the tree. `guml ast` and the conformance fingerprints
/// are supposed to show what the author wrote; a pass that invented four `option` children would make
/// every `select` case in the suite describe a document nobody wrote.
pub fn select_options(program: &Program, el: &Element) -> Vec<String> {
    let written: Vec<String> = el
        .children
        .iter()
        .filter(|c| c.tag == "option")
        .filter_map(|c| {
            c.content
                .clone()
                .or_else(|| c.label().map(str::to_string))
                .map(|s| s.trim().to_string())
        })
        .filter(|s| !s.is_empty())
        .collect();
    if !written.is_empty() {
        return written;
    }
    el.label()
        .and_then(|name| program.states.iter().find(|s| s.name == name))
        .map(|s| s.domain.clone())
        .unwrap_or_default()
}

pub fn row_bool_fields(program: &guml_ast::Program) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for r in &program.resources {
        let base = r.ty.trim_end_matches("[]");
        let Some(t) = program.types.iter().find(|t| t.name == base) else { continue };
        let mut bools = t.fields.iter().filter(|f| f.ty == "bool");
        if let (Some(f), None) = (bools.next(), bools.next()) {
            out.push((r.name.clone(), f.name.clone()));
        }
    }
    out
}

/// The row fields a free-text `where=` should search, or empty when this is not a free-text filter.
///
/// Both conditions have to hold, and the decision lives here rather than in each backend so React and
/// Svelte cannot disagree about what a document means:
///
/// 1. The bound state has **no domain and holds a string** — `state query=""`. A domain means the filter
///    is enumerated and `where_filter`'s existing cases apply; a number or a boolean is not a query.
/// 2. The row type has at least one **string** field to search. Searching a row of numbers for a
///    substring is not a filter anyone asked for, and returning nothing here means the caller warns
///    instead of emitting a predicate that can never match.
///
/// Declared field types are what decides it, not the field names: `{id, client, amount:number}` searches
/// `id` and `client` and leaves `amount` alone. A field with no declared type is a string, which is the
/// language's default and the reason it is spelled out in `guml_ast::Field`.
pub fn search_fields(program: &Program, resource: &str, filter: &str) -> Vec<String> {
    let Some(state) = program.states.iter().find(|s| s.name == filter) else { return Vec::new() };
    if !state.domain.is_empty() || !matches!(state.init, Value::Str(_)) {
        return Vec::new();
    }
    let Some(r) = program.resources.iter().find(|r| r.name == resource) else { return Vec::new() };
    let base = r.ty.trim_end_matches("[]");
    let Some(t) = program.types.iter().find(|t| t.name == base) else { return Vec::new() };
    t.fields
        .iter()
        .filter(|f| f.ty.is_empty() || f.ty == "string")
        .map(|f| f.name.clone())
        .collect()
}

/// The predicate chain for `where={state}`, or `None` when nothing in the domain can be filtered on.
///
/// `where=` filters a repeater by an enumerated state, so what it filters *by* has to be derived from
/// the domain and the row type together. Three cases, in order:
///
/// 1. **A boolean field.** A single `bool` on the row is a two-state flag, and the domain names its
///    states: `open` is the negation, `done` or the field's own name is the assertion. So
///    `state view=all|open|paid` over `{…, paid:bool}` filters on `paid` — which is the reading a
///    person gives it, and the reading the tabs imply.
/// 2. **A same-name field.** `where={area}` over a row with an `area` field compares them.
/// 3. **Neither**, and the caller warns.
///
/// The first case used to require the field be *named* `done`. That is the third place in this
/// compiler where the same hardcode sat — after the `.open`/`.done` aggregate and the body-less `save`
/// toggle — and here it did not produce a wrong filter but *no* filter: `all|open|paid` fell through
/// to case 3, so the tabs rendered, changed the state, and the table never responded.
///
/// Shared by React and Svelte deliberately. A fourth copy of this reasoning is a fourth chance for two
/// backends to filter the same document differently.
pub fn where_filter(
    source: &str,
    filter: &str,
    domain: &[String],
    fields: &[String],
    text_fields: &[String],
    flag: Option<&str>,
) -> Option<String> {
    // Case 0: a free-text query, from `search_fields` — a domain-less string state, so there is nothing
    // to enumerate and the filter is a substring match over the row's own text.
    //
    // Added because `where=` had refused it, honestly and unhelpfully: `input query` plus
    // `table contacts where={query}` produced two warnings and an unfiltered table, and "a searchable
    // table" is in half of GUML-Bench's categories. The alternative for an author was an escape hatch,
    // and `js` is component-body code — it cannot reach inside the repeater's `map`, so there was no
    // alternative at all.
    if !text_fields.is_empty() {
        let haystack = text_fields.iter().map(|f| format!("it.{f}")).collect::<Vec<_>>().join(", ");
        // An empty query renders everything rather than nothing: `"".includes` is true for every string,
        // which would work by accident here, but only until someone types a space. `trim` first and
        // short-circuit, so a whitespace-only query is also "no filter".
        return Some(format!(
            "{filter}.trim() === \"\"
        ? {source}
        : {source}.filter((it) =>
            [{haystack}].some((v) =>
              String(v).toLowerCase().includes({filter}.trim().toLowerCase()),
            ),
          )"
        ));
    }

    let members: Vec<&String> = domain.iter().filter(|m| *m != "all").collect();
    if members.is_empty() {
        return None;
    }

    // Case 1: every member describes the one boolean field. `flag` comes from the row *type* via
    // `row_bool_fields`, not from guessing at the field-name list — the names alone cannot tell a
    // boolean from a string.
    if let Some(flag) = flag {
        let boolean = |m: &str| match m {
            "open" => Some(format!("{source}.filter((it) => !it.{flag})")),
            _ if m == "done" || m == flag => Some(format!("{source}.filter((it) => it.{flag})")),
            _ => None,
        };
        if members.iter().all(|m| boolean(m).is_some()) {
            return Some(chain(source, filter, &members, |m| boolean(m).unwrap()));
        }
    }

    // Case 2: a row field of the same name holds the member.
    if fields.iter().any(|f| f == filter) {
        return Some(if domain.iter().any(|m| m == "all") {
            format!(
                "{filter} === \"all\" ? {source} : {source}.filter((it) => it.{filter} === {filter})"
            )
        } else {
            format!("{source}.filter((it) => it.{filter} === {filter})")
        });
    }

    None
}

/// A nested ternary, one branch per domain member, falling back to the unfiltered source.
///
/// Indented as the emitted file will read it: this is code a person opens.
fn chain(
    source: &str,
    filter: &str,
    members: &[&String],
    branch: impl Fn(&str) -> String,
) -> String {
    let mut out = String::new();
    for (i, m) in members.iter().enumerate() {
        let pad = "  ".repeat(i);
        let lead = if i == 0 { String::new() } else { format!("\n      {pad}: ") };
        let _ = write!(out, "{lead}{filter} === {m:?}\n      {pad}  ? {}", branch(m));
    }
    let pad = "  ".repeat(members.len().saturating_sub(1));
    let _ = write!(out, "\n      {pad}  : {source}");
    out
}

