/**
 * Generates lib/theme-classes.generated.ts — every utility class the compiler's theme can emit.
 *
 * # Why this file has to exist
 *
 * Tailwind generates only the classes it can find in your source. GUML's classes are decided by the
 * *theme* and produced by the *compiler at runtime*, so a live preview renders class names that were
 * never in any file Tailwind scanned. The result is not an obvious failure — it is a partially styled
 * preview. `border-slate-200`, `text-slate-900`, `rounded-xl` and `divide-slate-200` were all missing
 * from this site's stylesheet for exactly this reason, and the white surface behind the preview made
 * the result look plausible enough that nobody looked.
 *
 * Every host embedding GUML with a utility-class framework has this problem, which is why the compiler
 * answers it directly: `guml theme --classes` lists them, and this script writes them where Tailwind
 * can see them.
 *
 * Run `pnpm gen:theme` after changing the theme. `pnpm check:theme` fails if the file is stale.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const docsRoot = resolve(here, "..");
const repoRoot = resolve(docsRoot, "..");
const out = join(docsRoot, "lib", "theme-classes.generated.ts");

const classes = execFileSync(
  "cargo",
  ["run", "-q", "-p", "guml-cli", "--", "theme", "--classes"],
  { cwd: repoRoot, encoding: "utf8" },
)
  .split("\n")
  .map((l) => l.trim())
  .filter(Boolean);

if (classes.length < 40) {
  console.error(`only ${classes.length} classes returned — refusing to write a truncated list`);
  process.exit(1);
}

const body = `/**
 * GENERATED by scripts/gen-theme-classes.mjs — do not edit.
 *
 * Every utility class the compiler's active theme can emit. Tailwind scans this file (see the
 * \`@source\` list in app/globals.css) so those classes survive into the stylesheet; without it a live
 * preview renders class names that have no rule, and is silently half-styled.
 *
 * The strings are in an array rather than a template literal so the file stays diffable, and so a
 * reader can tell at a glance which classes the theme is responsible for.
 */
export const THEME_CLASSES = [
${classes.map((c) => `  "${c}",`).join("\n")}
] as const;
`;

const previous = (() => {
  try {
    return readFileSync(out, "utf8");
  } catch {
    return "";
  }
})();

if (process.argv.includes("--check")) {
  if (previous !== body) {
    console.error(
      "lib/theme-classes.generated.ts is stale — the theme changed without regenerating it.\n" +
        "Run: pnpm gen:theme",
    );
    process.exit(1);
  }
  console.log(`theme class list is current (${classes.length} classes)`);
} else {
  writeFileSync(out, body, "utf8");
  console.log(`wrote ${classes.length} theme classes to lib/theme-classes.generated.ts`);
}
