/**
 * The chatbot's system prompt is the *same* assembly the Phase 0 study measures
 * (`bench/phase0/lib/prompt.mjs`). If the product and the experiment prompt differently,
 * the experiment stops predicting the product — and the whole point of Phase 0 is that it
 * predicts something.
 *
 * Baked in at build time because the deployed site has no Rust toolchain to ask.
 */
function chatPrompt() {
  try {
    return systemPrompt({ examples: 3 });
  } catch (e) {
    console.warn(`! could not assemble the chat system prompt: ${e.message}`);
    return "";
  }
}

