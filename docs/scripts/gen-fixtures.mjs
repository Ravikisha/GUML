/** Compile a fixture with the real compiler so "emitted" is never stale. */
function compile(file) {
  try {
    return execFileSync(
      "cargo",
      ["run", "-q", "-p", "guml-cli", "--", "build", `fixtures/${file}`],
      { cwd: repoRoot, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    ).replace(/\r\n/g, "\n");
  } catch {
    console.warn(`! could not compile ${file} (is the Rust toolchain available?)`);
    return null;
  }
}

